/** Narrows any locale string ("sv-SE", "AR", null) to a supported PDF locale. */
export function resolvePdfLocale(locale: string | null | undefined): PdfLocale {
  const base = String(locale ?? '')
    .toLowerCase()
    .split(/[-_]/)[0];
  return (PDF_LOCALES as readonly string[]).includes(base)
    ? (base as PdfLocale)
    : 'en';
}

export function getInvoicePhrases(
  locale: string | null | undefined,
): InvoicePhrases {
  return INVOICE_PHRASES[resolvePdfLocale(locale)];
}

/**
 * Fills `{name}` placeholders. Values are inserted verbatim, so callers that
 * build HTML must pass already-escaped values (the template does).
 */
export function fillPhrase(
  phrase: string,
  vars: Record<string, string | number>,
): string {
  return phrase.replace(/\{(\w+)\}/g, (m, k: string) =>
    k in vars ? String(vars[k]) : m,
  );
}
