import { randomBytes } from 'crypto';

// Settings of the `feeds` store app (M5.6), kept in StoreApp.settings. Two
// readers, like the other apps: a lenient parse for the runtime (odd values
// fall back to defaults, never throws) and a strict validation for the
// dashboard write (PUT /stores/my/apps/feeds -> STORE_APP_SETTINGS_INVALID).

export interface FeedsSettings {
  /** Serve the Google Merchant RSS feed. */
  google: boolean;
  /** Serve the Meta (Facebook / Instagram) catalog CSV. */
  facebook: boolean;
  /** Brand used for products without their own `brand`. */
  default_brand: string | null;
  /**
   * Secret path segment of the public feed URLs; 32 chars, generated by the
   * API (ensureToken / rotate), never typed by hand. Null until first use.
   */
  token: string | null;
  /** One item per variant (item_group_id = product) instead of per product. */
  include_variants: boolean;
  /** Google `g:shipping` service label (e.g. "Standard"); none when null. */
  shipping_label: string | null;
}

export const FEEDS_LIMITS = {
  token_length: 32,
  default_brand_length: 70,
  shipping_label_length: 100,
} as const;

export const DEFAULT_FEEDS_SETTINGS: Readonly<FeedsSettings> = Object.freeze({
  google: true,
  facebook: true,
  default_brand: null,
  token: null,
  include_variants: true,
  shipping_label: null,
});

const TOKEN_RE = /^[a-f0-9]{32}$/;

/** A fresh feed token: 32 lower-case hex chars (128 bits). */
export function generateFeedToken(): string {
  return randomBytes(FEEDS_LIMITS.token_length / 2).toString('hex');
}

export function isFeedToken(value: unknown): value is string {
  return typeof value === 'string' && TOKEN_RE.test(value);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

function optionalText(value: unknown, maxLen: number): string | null {
  if (typeof value !== 'string') return null;
  const s = value.trim().slice(0, maxLen);
  return s ? s : null;
}

/** Lenient read: defaults merged, invalid keys replaced by their default. */
export function normalizeFeedsSettings(raw: unknown): FeedsSettings {
  const d = DEFAULT_FEEDS_SETTINGS;
  const r = isRecord(raw) ? raw : {};
  const bool = (key: keyof FeedsSettings, def: boolean) =>
    typeof r[key] === 'boolean' ? (r[key] as boolean) : def;
  return {
    google: bool('google', d.google),
    facebook: bool('facebook', d.facebook),
    default_brand: optionalText(
      r.default_brand,
      FEEDS_LIMITS.default_brand_length,
    ),
    token: isFeedToken(r.token) ? r.token : null,
    include_variants: bool('include_variants', d.include_variants),
    shipping_label: optionalText(
      r.shipping_label,
      FEEDS_LIMITS.shipping_label_length,
    ),
  };
}

const KNOWN_KEYS: ReadonlySet<string> = new Set(
  Object.keys(DEFAULT_FEEDS_SETTINGS),
);

/**
 * Strict write validation. Every key is optional, a present known key must
 * be valid, an unknown key is an error. The token, when present, must be a
 * generated one (32 hex chars) or null: the dashboard sends the stored
 * token back unchanged and rotates it through POST feeds/my/token/rotate.
 */
export function validateFeedsSettings(raw: unknown): {
  ok: boolean;
  errors: string[];
} {
  if (!isRecord(raw)) {
    return { ok: false, errors: ['settings must be an object.'] };
  }
  const errors: string[] = [];
  for (const key of Object.keys(raw)) {
    if (!KNOWN_KEYS.has(key)) errors.push(`Unknown setting "${key}".`);
  }
  for (const key of ['google', 'facebook', 'include_variants']) {
    if (key in raw && typeof raw[key] !== 'boolean') {
      errors.push(`${key} must be true or false.`);
    }
  }
  const textKeys: [string, number][] = [
    ['default_brand', FEEDS_LIMITS.default_brand_length],
    ['shipping_label', FEEDS_LIMITS.shipping_label_length],
  ];
  for (const [key, maxLen] of textKeys) {
    if (!(key in raw) || raw[key] === null) continue;
    const v = raw[key];
    if (typeof v !== 'string' || v.trim().length > maxLen) {
      errors.push(`${key} must be a text of at most ${maxLen} characters.`);
    }
  }
  if ('token' in raw && raw.token !== null && !isFeedToken(raw.token)) {
    errors.push(
      `token must be a generated ${FEEDS_LIMITS.token_length}-character token (use "Rotate token").`,
    );
  }
  return { ok: errors.length === 0, errors };
}
